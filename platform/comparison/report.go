// Package comparison
// Sprint 10: Automated comparison report — markdown tables, per-vendor
// breakdown, executive summary, and release-note-ready output.
package comparison

import (
	"fmt"
	"strings"
	"time"
)

// ====================================================================
// Report Generation
// ====================================================================

// ComparisonReport is the full automated comparison report.
type ComparisonReport struct {
	// Title for the report header.
	Title string `json:"title"`

	// GeneratedAt is when this report was produced.
	GeneratedAt time.Time `json:"generated_at"`

	// GraphLayerVersion is the GraphLayer release version.
	GraphLayerVersion string `json:"graphlayer_version"`

	// ReferenceVersion is the reference version being compared against.
	ReferenceVersion string `json:"reference_version"`

	// Metrics holds the quantified comparison results.
	Metrics *ComparisonMetrics `json:"metrics"`

	// Summary is a 1–3 sentence executive summary.
	Summary string `json:"summary"`

	// Recommendations are actionable findings.
	Recommendations []string `json:"recommendations"`
}

// GenerateReport creates a full comparison report from metrics.
func GenerateReport(
	title, glVersion, referenceVersion string,
	metrics *ComparisonMetrics,
) *ComparisonReport {
	r := &ComparisonReport{
		Title:              title,
		GeneratedAt:        time.Now(),
		GraphLayerVersion:  glVersion,
		ReferenceVersion:      referenceVersion,
		Metrics:            metrics,
		Summary:            generateSummary(metrics),
		Recommendations:    generateRecommendations(metrics),
	}
	return r
}

// RenderMarkdown produces a markdown-formatted comparison report.
// Suitable for release notes, CI output, and documentation.
func (r *ComparisonReport) RenderMarkdown() string {
	var b strings.Builder

	// Header
	b.WriteString(fmt.Sprintf("# %s\n\n", r.Title))
	b.WriteString(fmt.Sprintf("**Generated:** %s  \n", r.GeneratedAt.Format(time.RFC3339)))
	b.WriteString(fmt.Sprintf("**GraphLayer:** %s  |  **reference:** %s\n\n", r.GraphLayerVersion, r.ReferenceVersion))

	// Executive summary
	b.WriteString("## Executive Summary\n\n")
	b.WriteString(r.Summary + "\n\n")

	// Overall score badge
	score := r.Metrics.OverallScore
	badge := scoreToBadge(score)
	b.WriteString(fmt.Sprintf("**Overall Score:** %.1f%% %s\n\n", score*100, badge))

	// Device accuracy
	b.WriteString("## Device Accuracy\n\n")
	b.WriteString(renderDeviceTable(r.Metrics.DeviceMetrics))

	// Link accuracy
	b.WriteString("## Link Accuracy\n\n")
	b.WriteString(renderLinkTable(r.Metrics.LinkMetrics))

	// Vendor coverage
	b.WriteString("## Vendor Coverage\n\n")
	b.WriteString(renderVendorTable(r.Metrics.VendorCoverage))

	// Evidence quality
	b.WriteString("## Evidence Quality\n\n")
	b.WriteString(renderEvidenceTable(r.Metrics.EvidenceQuality))

	// False positive analysis
	b.WriteString("## False Positive Analysis\n\n")
	b.WriteString(renderFPTable(r.Metrics.FalsePositives))

	// Per-vendor breakdown
	if len(r.Metrics.PerVendor) > 0 {
		b.WriteString("## Per-Vendor Breakdown\n\n")
		b.WriteString(renderVendorBreakdownTable(r.Metrics.PerVendor))
	}

	// Recommendations
	if len(r.Recommendations) > 0 {
		b.WriteString("## Recommendations\n\n")
		for _, rec := range r.Recommendations {
			b.WriteString(fmt.Sprintf("- %s\n", rec))
		}
		b.WriteString("\n")
	}

	// Methodology note
	b.WriteString("## Methodology\n\n")
	b.WriteString("Devices are matched by serial number, management IP, and hostname (in priority order). ")
	b.WriteString("Links are matched by endpoint device IDs and port names with fuzzy fallback matching. ")
	b.WriteString("The overall score is a weighted composite: device F1 (30%), link F1 (25%), ")
	b.WriteString("vendor breadth (15%), evidence quality (20%), false-positive rate inversion (10%).\n\n")

	b.WriteString("---\n*Report generated by GraphLayer reference Comparison Harness (Sprint 10)*\n")

	return b.String()
}

// RenderJSON produces a JSON report for programmatic consumption.
func (r *ComparisonReport) RenderJSON() string {
	// This is a placeholder — in production, use encoding/json.
	return fmt.Sprintf(`{"title":"%s","overall_score":%.4f,"summary":"%s"}`,
		r.Title, r.Metrics.OverallScore, r.Summary)
}

