func generateSummary(m *ComparisonMetrics) string {
	var parts []string

	if m.DeviceMetrics.F1Score >= 0.90 {
		parts = append(parts,
			fmt.Sprintf("GraphLayer achieves excellent device detection (F1=%.0f%%)",
				m.DeviceMetrics.F1Score*100))
	} else if m.DeviceMetrics.F1Score >= 0.70 {
		parts = append(parts,
			fmt.Sprintf("GraphLayer shows good device detection (F1=%.0f%%)",
				m.DeviceMetrics.F1Score*100))
	}

	if m.VendorCoverage.GraphLayerVendorCount > m.VendorCoverage.ReferenceVendorCount {
		parts = append(parts,
			fmt.Sprintf("with broader vendor coverage (%d vs %d vendors)",
				m.VendorCoverage.GraphLayerVendorCount,
				m.VendorCoverage.ReferenceVendorCount))
	}

	if m.EvidenceQuality.EvidenceQualityScore > 1.0 {
		parts = append(parts, "and superior evidence provenance")
	}

	if m.FalsePositives.GraphLayerFPRate < 0.05 {
		parts = append(parts,
			fmt.Sprintf("with low false positives (%.1f%%)",
				m.FalsePositives.GraphLayerFPRate*100))
	}

	if len(parts) == 0 {
		return fmt.Sprintf("GraphLayer demonstrates competitive performance against reference with an overall score of %.1f%%.",
			m.OverallScore*100)
	}

	return strings.Join(parts, ", ") + "."
}

func generateRecommendations(m *ComparisonMetrics) []string {
	recs := make([]string, 0)

	if m.DeviceMetrics.MissingDevices > 0 {
		recs = append(recs, fmt.Sprintf(
			"Investigate %d devices found by reference but missed by GraphLayer — check for unparsed vendor families or missing connectors.",
			m.DeviceMetrics.MissingDevices))
	}

	if m.LinkMetrics.MissingLinks > 0 {
		recs = append(recs, fmt.Sprintf(
			"Review %d links found by reference but missed by GraphLayer — may indicate missing L2 topology inference or LLDP parsing gaps.",
			m.LinkMetrics.MissingLinks))
	}

	if m.FalsePositives.GraphLayerFPRate > 0.05 {
		recs = append(recs, fmt.Sprintf(
			"False-positive rate of %.1f%% exceeds 5%% threshold — audit unmatched devices for duplicate detection or evidence quality issues.",
			m.FalsePositives.GraphLayerFPRate*100))
	}

	if len(m.VendorCoverage.MissingVendors) > 0 {
		recs = append(recs, fmt.Sprintf(
			"Vendor gap detected: %s — consider adding parsers for these vendor families.",
			strings.Join(m.VendorCoverage.MissingVendors, ", ")))
	}

	if m.EvidenceQuality.GraphLayerAvgConfidence < 0.60 {
		recs = append(recs,
			"Average confidence is below 60% — add more operational data collection or config parsing to improve confidence.")
	}

	return recs
}

// ====================================================================
// Helpers
// ====================================================================

func scoreToBadge(score float64) string {
	switch {
	case score >= 0.90:
		return "🏆 Excellent"
	case score >= 0.75:
		return "✅ Good"
	case score >= 0.60:
		return "⚠️ Fair"
	default:
		return "❌ Needs Improvement"
	}
}

func sortedVendorBreakdowns(m map[string]VendorBreakdown) []VendorBreakdown {
	out := make([]VendorBreakdown, 0, len(m))
	for _, vb := range m {
		out = append(out, vb)
	}
	// Sort by vendor name
	for i := 1; i < len(out); i++ {
		j := i
		for j > 0 && out[j].Vendor < out[j-1].Vendor {
			out[j], out[j-1] = out[j-1], out[j]
			j--
		}
	}
	return out
}
